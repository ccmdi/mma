// Renders the compiled manual chapters to plain text and writes the search index as a
// generated module, keeping react-dom/server and the MDX set out of the client bundle.

import { writeFileSync, mkdtempSync, rmSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { build } from "vite";

const here = dirname(fileURLToPath(import.meta.url));
const app = join(here, "..");
const outFile = join(app, "src", "components", "manual", "manual-index.gen.ts");
// Under node_modules so Node resolves react/react-dom from the app, not from a temp dir.
const outDir = mkdtempSync(join(app, "node_modules", ".mma-manual-index-"));

try {
	await build({
		root: app,
		configFile: join(app, "vite.config.ts"),
		logLevel: "warn",
		build: {
			ssr: join(app, "src", "components", "manual", "indexSource.ts"),
			outDir,
			emptyOutDir: true,
			minify: false,
		},
	});
	const entry = pathToFileURL(join(outDir, "indexSource.js")).href;
	const { buildIndex } = await import(entry);
	const index = buildIndex();
	if (index.length === 0) throw new Error("no manual chapters were rendered");

	const body = index.map((c) => `\t${JSON.stringify(c)},`).join("\n");
	writeFileSync(
		outFile,
		"// AUTO-GENERATED by gen:manual-index. Do not edit by hand.\n" +
			'import type { ChapterText } from "@/components/manual/chapters";\n\n' +
			"export const MANUAL_INDEX: ChapterText[] = [\n" +
			body +
			"\n];\n",
	);
	console.log(`gen:manual-index: ${index.length} chapters`);
} finally {
	rmSync(outDir, { recursive: true, force: true });
}
