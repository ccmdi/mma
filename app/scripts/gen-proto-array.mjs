// Generates the message shapes and their array-JSON reader from a .proto, alongside the
// binary reader pbf generates.
//
// SingleImageSearch answers the same messages GetMetadata does, encoded as array-JSON
// ("json+protobuf"): a JSON array whose element positions are the field numbers, so index
// i holds field i+1. That mapping is mechanical, so this comes from the schema rather than
// being hand-written a second time.
//
//   node scripts/gen-proto-array.mjs src/lib/proto/getmetadata.proto > out.ts
import parse from "protocol-buffers-schema";
import { readFileSync } from "node:fs";

const READ = {
	double: "num", float: "num", int32: "num", int64: "num", uint32: "num", uint64: "num",
	sint32: "num", sint64: "num", fixed32: "num", fixed64: "num", bool: "bool", string: "str",
};
const TS = {
	double: "number", float: "number", int32: "number", int64: "number", uint32: "number",
	uint64: "number", sint32: "number", sint64: "number", fixed32: "number", fixed64: "number",
	bool: "boolean", string: "string",
};
const HELPERS = {
	list: "const list = (v: unknown): unknown[] => (Array.isArray(v) ? v : []);",
	msg: "const msg = (v: unknown): unknown[] | undefined => (Array.isArray(v) ? v : undefined);",
	num: 'const num = (v: unknown): number => (typeof v === "number" ? v : 0);',
	str: 'const str = (v: unknown): string => (typeof v === "string" ? v : "");',
	bool: "const bool = (v: unknown): boolean => v === true;",
};

const file = process.argv[2];
const schema = parse(readFileSync(file, "utf8"));
const names = new Set(schema.messages.map((m) => m.name));
const base = file.split("/").pop();

const declare = (f) => {
	const t = names.has(f.type) ? f.type : TS[f.type];
	if (!t) throw new Error(`${f.name}: unsupported type ${f.type}`);
	return `\t${f.name}: ${f.repeated ? `${t}[]` : names.has(f.type) ? `${t} | undefined` : t};`;
};

const read = (f) => {
	const slot = `a[${f.tag - 1}]`;
	if (names.has(f.type)) {
		return f.repeated
			? `list(${slot}).map((e) => read${f.type}(e))`
			: `msg(${slot}) && read${f.type}(${slot})`;
	}
	const kind = READ[f.type];
	if (!kind) throw new Error(`${f.name}: unsupported type ${f.type}`);
	return f.repeated ? `list(${slot}).map((e) => ${kind}(e))` : `${kind}(${slot})`;
};

const interfaces = schema.messages
	.map((m) => `export interface ${m.name} {\n${m.fields.map(declare).join("\n")}\n}`)
	.join("\n\n");

const readers = schema.messages
	.map((m) => {
		const fields = m.fields.map((f) => `\t\t${f.name}: ${read(f)},`).join("\n");
		return `export function read${m.name}(v: unknown): ${m.name} {\n\tconst a = list(v);\n\treturn {\n${fields}\n\t};\n}`;
	})
	.join("\n\n");

const helpers = Object.entries(HELPERS)
	.filter(([k]) => k === "list" || readers.includes(`${k}(`))
	.map(([, src]) => src)
	.join("\n");

process.stdout.write(`// code generated by scripts/gen-proto-array.mjs from ${base}
// The message shapes, plus readers for their array-JSON ("json+protobuf") form, in which
// index i holds field i+1. Do not edit.

${interfaces}

${helpers}

${readers}
`);
